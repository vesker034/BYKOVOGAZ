def _find_otzyv_paragraph_index(doc) -> int:
    for i, p in enumerate(doc.paragraphs):
        if p.text.strip() == "ОТЗЫВ":
            return i
    raise ValueError('В документе не найден абзац «ОТЗЫВ» (якорь вставки).')


def _sections_26_11_already_present(doc, otzyv_idx: int) -> bool:
    """Не дублировать вставку, если перед «ОТЗЫВ» уже есть подзаголовок 2.6."""
