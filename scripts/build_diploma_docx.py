def build():
    doc = Document(str(SOURCE))
    ref_body = doc.paragraphs[REF_BODY]
    insert_before = _find_otzyv_paragraph_index(doc)
    if _sections_26_11_already_present(doc, insert_before):
        print(
            "Разделы 2.6–2.11 уже есть перед «ОТЗЫВ», вставка не выполнялась. "
            f"Файл: {OUTPUT}"
        )
        shutil.copy2(DOC_MAIN, DOC_COPY)
        print(f"Копия синхронизирована: {DOC_COPY}")
        return

    blocks = [b.strip() for b in SECTIONS.split("\n\n") if b.strip()]

    # вставляем в обратном порядке, чтобы сохранить прямой порядок абзацев
    for block in reversed(blocks):
        if block.startswith("Рисунок "):
            add_figure_caption_before(doc, insert_before, block)
            try:
                num = int(block.split(".")[0].replace("Рисунок ", "").strip())
            except ValueError:
                num = None
            if num and num in FIGURE_PLACEHOLDERS:
                add_placeholder_before(doc, insert_before, FIGURE_PLACEHOLDERS[num])
            add_figure_spacer_before(doc, insert_before)
        elif block[0:3].replace(".", "").isdigit() and " " in block[:8]:
            add_heading_before(doc, insert_before, block)
        else:
            add_paragraph_before(doc, insert_before, block, ref_body)

    doc.save(str(OUTPUT))
    print(f"Сохранено: {OUTPUT}")
    shutil.copy2(DOC_MAIN, DOC_COPY)
    print(f"Копия: {DOC_COPY}")


if __name__ == "__main__":
    build()
